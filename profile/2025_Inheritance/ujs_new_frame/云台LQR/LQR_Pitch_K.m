function K = LQR_Pitch_K(l)
% PITCH_LQR_K
%     K = PITCH_LQR_K(l)
%
% 输入参数：
%     l - 杆长（单位：m）
% 输出参数：
%     K - 反馈增益矩阵 [k1, k2]

    % 三次多项式系数
    p_k1 = [7.413870e+03, -4.031148e+03, 7.181158e+02, -4.216120e+01];
    p_k2 = [4.741146e+02, -2.567006e+02, 4.546998e+01, -2.653463e+00];

    % 计算增益
    k1 = polyval(p_k1, l);
    k2 = polyval(p_k2, l);
    
    K = [k1, k2];
end