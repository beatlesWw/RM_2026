  MX_CAN1_Init();
  /* USER CODE BEGIN 2 */
  can_filter_init();
  PID_init(&pid, 0, PID, max_out, max_iout);   
  HAL_GPIO_WritePin(GPIOA,GPIO_PIN_0, GPIO_PIN_SET); 
   int last_key_state = 1; // 1:松开, 0:按下
   fp32 set = 0; // 初始目标位置
   int flag = 0; // 用于标记是否按下 
  /* USER CODE END 2 */

